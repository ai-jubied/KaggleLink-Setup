#!/bin/bash
#
# start_code_server.sh - run code-server in the background and expose it via a
# PUBLIC zrok share, so the editor is reachable from any browser.
#
# Two auto-restart supervisors are installed: one for code-server itself and
# one for the public zrok share. Both survive as long as the Kaggle session is
# alive. The public share is ephemeral, so its URL changes if it restarts.
#
# Usage: ./start_code_server.sh <zrok_token> [port] [workspace_dir]
#
set -euo pipefail

ZROK_TOKEN=${1:?Usage: ./start_code_server.sh <zrok_token> [port] [workspace_dir]}
CODE_PORT=${2:-8080}
WORKSPACE=${3:-$(cat /root/.kagglelink_code_workspace 2>/dev/null || echo /kaggle/working)}

GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
BLUE='\033[0;34m'
BOLD='\033[1m'
NC='\033[0m'

LOG_DIR="/var/log/kagglelink"
CODE_LOG="$LOG_DIR/code-server.log"
CODE_ZROK_LOG="$LOG_DIR/zrok-code.log"
CODE_SUP="/usr/local/bin/kagglelink-code-run"
CODE_ZROK_SUP="/usr/local/bin/kagglelink-code-zrok-run"
URLFILE="/root/.kagglelink_code_url"
mkdir -p "$LOG_DIR"

if ! command -v code-server >/dev/null 2>&1; then
    echo -e "${RED}code-server not installed. Run setup_code_server.sh first.${NC}"
    exit 1
fi

# --- Ensure zrok is enabled (idempotent) --------------------------------
if zrok status 2>/dev/null | grep -q '<<SET>>'; then
    echo -e "${BLUE}zrok already enabled; skipping enable.${NC}"
else
    echo -e "${BLUE}Enabling zrok with provided token...${NC}"
    zrok enable "$ZROK_TOKEN" || {
        echo -e "${RED}Failed to enable zrok with the provided token.${NC}"
        exit 1
    }
fi

# --- code-server supervisor ---------------------------------------------
cat > "$CODE_SUP" <<EOF
#!/bin/bash
# Auto-generated by start_code_server.sh - restarts code-server if it drops.
LOG="$CODE_LOG"
while true; do
    echo "[\$(date '+%F %T')] starting code-server on 127.0.0.1:${CODE_PORT}" >> "\$LOG"
    code-server "$WORKSPACE" >> "\$LOG" 2>&1
    echo "[\$(date '+%F %T')] code-server exited; restarting in 5s" >> "\$LOG"
    sleep 5
done
EOF
chmod +x "$CODE_SUP"

# --- public zrok share supervisor ---------------------------------------
cat > "$CODE_ZROK_SUP" <<EOF
#!/bin/bash
# Auto-generated by start_code_server.sh - restarts the public share if it drops.
LOG="$CODE_ZROK_LOG"
ATTEMPT=0
while [ "\$ATTEMPT" -lt 100 ]; do
    ATTEMPT=\$((ATTEMPT + 1))
    echo "[\$(date '+%F %T')] starting public zrok share (attempt \$ATTEMPT)" >> "\$LOG"
    zrok share public --headless --backend-mode proxy "http://localhost:${CODE_PORT}" >> "\$LOG" 2>&1
    echo "[\$(date '+%F %T')] public share exited; restarting in 5s" >> "\$LOG"
    sleep 5
done
EOF
chmod +x "$CODE_ZROK_SUP"

# --- Kill only our own previous code-server processes -------------------
pkill -f "kagglelink-code-run"      2>/dev/null || true
pkill -f "kagglelink-code-zrok-run" 2>/dev/null || true
pkill -f "zrok share public"        2>/dev/null || true
pkill -f "code-server"              2>/dev/null || true
sleep 1

echo -e "${BLUE}Starting code-server in the background (port ${CODE_PORT})...${NC}"
: > "$CODE_LOG"; : > "$CODE_ZROK_LOG"
nohup setsid "$CODE_SUP" >/dev/null 2>&1 &

# Wait for code-server to be listening before publishing the share
for _ in $(seq 1 30); do
    if curl -sf "http://127.0.0.1:${CODE_PORT}/healthz" >/dev/null 2>&1; then break; fi
    sleep 2
done

echo -e "${BLUE}Publishing code-server via a public zrok share...${NC}"
nohup setsid "$CODE_ZROK_SUP" >/dev/null 2>&1 &

# --- Grab the public URL from the log -----------------------------------
PUBLIC_URL=""
for _ in $(seq 1 30); do
    PUBLIC_URL=$(grep -oiE 'https://[a-z0-9.-]+\.zrok\.io[a-z0-9/._-]*' "$CODE_ZROK_LOG" 2>/dev/null | tail -n 1 || true)
    [ -n "$PUBLIC_URL" ] && break
    sleep 2
done
[ -n "$PUBLIC_URL" ] && printf '%s\n' "$PUBLIC_URL" > "$URLFILE"

PASS=$(cat /root/.kagglelink_code_password 2>/dev/null || echo "(see setup output)")

sleep 2
if ! pgrep -f "code-server" >/dev/null; then
    echo -e "${RED}code-server does not appear to be running. Last log lines:${NC}"
    tail -n 20 "$CODE_LOG"
    exit 1
fi

echo ""
echo -e "${GREEN}${BOLD}Browser VS Code is up.${NC}"
if [ -n "$PUBLIC_URL" ]; then
    echo -e "${GREEN}Open in any browser:${NC} ${BOLD}${PUBLIC_URL}${NC}"
else
    echo -e "${YELLOW}Could not detect the public URL yet. Check the log:${NC} tail -f $CODE_ZROK_LOG"
fi
echo -e "${GREEN}Password:${NC} ${BOLD}${PASS}${NC}"
echo -e "${BLUE}code-server log: ${CODE_LOG} | public share log: ${CODE_ZROK_LOG}${NC}"
