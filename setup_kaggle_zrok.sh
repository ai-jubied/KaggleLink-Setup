#!/bin/bash
#
# setup_kaggle_zrok.sh - install and configure sshd + zrok on a Kaggle instance
#
# Usage: ./setup_kaggle_zrok.sh <authorized_keys_url> [ssh_port] [zrok_version]
#
set -euo pipefail

AUTH_KEYS_URL=${1:?Usage: ./setup_kaggle_zrok.sh <authorized_keys_url> [ssh_port] [zrok_version]}
SSH_PORT=${2:-22}
ZROK_VERSION=${3:-latest}          # "latest" resolves via GitHub redirect, or pin e.g. v2.0.4
FALLBACK_ZROK_VERSION="v2.0.4"

ENV_FILE="/root/.kagglelink_env"
LOG_DIR="/var/log/kagglelink"
SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" &>/dev/null && pwd)

log() { echo "[kagglelink] $*"; }

setup_ssh_directory() {
    log "Setting up SSH directory in $HOME/.ssh..."
    local ssh_dir_path="$HOME/.ssh"
    mkdir -p "$ssh_dir_path"
    if wget -q --tries=3 --timeout=30 -O "$ssh_dir_path/authorized_keys" "$AUTH_KEYS_URL"; then
        chmod 700 "$ssh_dir_path"
        chmod 600 "$ssh_dir_path/authorized_keys"
        if ! grep -qE '^(ssh|ecdsa)-' "$ssh_dir_path/authorized_keys"; then
            log "ERROR: downloaded file does not look like an authorized_keys file (no public key found)."
            log "Check that $AUTH_KEYS_URL points to the RAW public key file."
            exit 1
        fi
        log "authorized_keys installed ($(grep -cE '^(ssh|ecdsa)-' "$ssh_dir_path/authorized_keys") key(s))"
    else
        log "ERROR: failed to download authorized keys from $AUTH_KEYS_URL"
        exit 1
    fi
}

copy_vscode_dir() {
    local vscode_dir_in_repo="$SCRIPT_DIR/.vscode"
    if [ -d "$vscode_dir_in_repo" ]; then
        local target
        for target in /kaggle /kaggle/working; do
            mkdir -p "$target/.vscode"
            cp -r "$vscode_dir_in_repo/." "$target/.vscode/"
        done
        log ".vscode settings copied to /kaggle and /kaggle/working"
    else
        log "WARNING: .vscode directory not found at $vscode_dir_in_repo (skipping)"
    fi
}

configure_sshd() {
    mkdir -p /var/run/sshd
    log "Writing sshd_config (port ${SSH_PORT})..."

    if [ -s /etc/ssh/sshd_config ] && [ ! -f /etc/ssh/sshd_config.backup ]; then
        cp /etc/ssh/sshd_config /etc/ssh/sshd_config.backup
        log "Original sshd_config backed up to /etc/ssh/sshd_config.backup"
    fi

    cat <<EOF >/etc/ssh/sshd_config
# SSH configuration generated by kagglelink
Port ${SSH_PORT}
PermitRootLogin prohibit-password
PasswordAuthentication no
PubkeyAuthentication yes
AuthorizedKeysFile %h/.ssh/authorized_keys
PermitEmptyPasswords no
StrictModes yes
MaxAuthTries 3
MaxSessions 10

# Connection settings
TCPKeepAlive yes
ClientAliveInterval 30
ClientAliveCountMax 3
Compression yes
UseDNS no

# Forwarding (local port-forwarding for Jupyter/TensorBoard etc.)
X11Forwarding yes
X11DisplayOffset 10
AllowTcpForwarding yes
GatewayPorts no
PermitTunnel no

# Authentication settings
IgnoreRhosts yes
HostbasedAuthentication no
ChallengeResponseAuthentication no
UsePAM yes

# Logging
SyslogFacility AUTH
LogLevel INFO
PrintLastLog yes

# Environment
AcceptEnv LANG LC_* EDITOR VISUAL

# Rate limiting
MaxStartups 10:30:60

# Modern ciphers and algorithms
Ciphers chacha20-poly1305@openssh.com,aes256-gcm@openssh.com,aes128-gcm@openssh.com,aes256-ctr,aes192-ctr,aes128-ctr
KexAlgorithms curve25519-sha256,curve25519-sha256@libssh.org,diffie-hellman-group16-sha512,diffie-hellman-group18-sha512,diffie-hellman-group-exchange-sha256
MACs hmac-sha2-256-etm@openssh.com,hmac-sha2-512-etm@openssh.com,umac-128-etm@openssh.com
EOF
    log "sshd_config written."
}

setup_environment_variables() {
    log "Snapshotting Kaggle environment for SSH sessions -> $ENV_FILE"
    {
        echo "# Kaggle environment snapshot (regenerated on each setup run by kagglelink)"
        while IFS='=' read -r -d '' key value; do
            # skip invalid identifiers and shell-managed/noisy variables
            [[ "$key" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]] || continue
            case "$key" in
                PWD|OLDPWD|SHLVL|_|HOME|PS1|PS2|HOSTNAME|TERM|LS_COLORS|SHELL) continue ;;
            esac
            printf 'export %s=%q\n' "$key" "$value"
        done < <(env -0)
    } > "$ENV_FILE"
    chmod 600 "$ENV_FILE"

    # Idempotent: only append the loader block to .bashrc once
    if ! grep -q 'kagglelink_env' /root/.bashrc 2>/dev/null; then
        {
            echo ''
            echo '# >>> kagglelink >>>'
            echo '[ -f /root/.kagglelink_env ] && . /root/.kagglelink_env'
            cat <<'EOT'
# Dynamic VS Code server path resolution
if [ -d "$HOME/.vscode-server/cli/servers" ]; then
  VSCODE_SERVER_DIR=$(find "$HOME/.vscode-server/cli/servers" -maxdepth 1 -type d -name "Stable-*" | sort | tail -n 1)
  [ -n "$VSCODE_SERVER_DIR" ] && export PATH="$VSCODE_SERVER_DIR/server/bin/remote-cli:$PATH"
fi
EOT
            echo '# <<< kagglelink <<<'
        } >> /root/.bashrc
        log "Loader block added to /root/.bashrc"
    else
        log "/root/.bashrc already configured (skipping)"
    fi
}

install_packages() {
    if command -v sshd &>/dev/null; then
        log "openssh-server already installed (skipping apt)"
        return
    fi
    log "Installing openssh-server..."
    apt-get update -qq
    DEBIAN_FRONTEND=noninteractive apt-get install -y -qq openssh-server
}

resolve_zrok_version() {
    if [ "$ZROK_VERSION" != "latest" ]; then
        echo "$ZROK_VERSION"
        return
    fi
    # Rate-limit-free: read the tag from the releases/latest redirect
    local tag
    tag=$(curl -sI https://github.com/openziti/zrok/releases/latest | tr -d '\r' \
          | awk -F/ 'tolower($1) ~ /^location:/ {print $NF}')
    if [ -n "$tag" ]; then
        echo "$tag"
    else
        log "WARNING: could not resolve latest zrok version; falling back to $FALLBACK_ZROK_VERSION" >&2
        echo "$FALLBACK_ZROK_VERSION"
    fi
}

install_zrok() {
    if command -v zrok &>/dev/null; then
        log "zrok already installed: $(zrok version 2>/dev/null | head -n 1); skipping install"
        return
    fi
    local version tarball url tmpdir
    version=$(resolve_zrok_version)
    tarball="zrok_${version#v}_linux_amd64.tar.gz"
    url="https://github.com/openziti/zrok/releases/download/${version}/${tarball}"
    tmpdir=$(mktemp -d)

    log "Downloading zrok ${version}..."
    if ! wget -q --tries=3 --timeout=60 -O "$tmpdir/$tarball" "$url"; then
        rm -rf "$tmpdir"
        log "ERROR: failed to download $url"
        exit 1
    fi

    if ! tar -xzf "$tmpdir/$tarball" -C "$tmpdir"; then
        rm -rf "$tmpdir"
        log "ERROR: failed to extract zrok archive"
        exit 1
    fi

    if [ ! -f "$tmpdir/zrok" ]; then
        rm -rf "$tmpdir"
        log "ERROR: zrok binary not found in archive"
        exit 1
    fi

    install -m 755 "$tmpdir/zrok" /usr/local/bin/zrok
    rm -rf "$tmpdir"

    if ! zrok version &>/dev/null; then
        log "ERROR: zrok install verification failed"
        exit 1
    fi
    log "zrok installed: $(zrok version | head -n 1)"
}

install_helper_commands() {
    log "Installing helper commands to /usr/local/bin..."
    local name
    for name in install_extensions kagglelink-status; do
        local src="$SCRIPT_DIR/${name}.sh"
        if [ -f "$src" ]; then
            install -m 755 "$src" "/usr/local/bin/$name"
            log "  $name -> available in PATH"
        else
            log "  WARNING: $src not found; '$name' command not installed"
        fi
    done
}

setup_default_directory() {
    log "Installing default-directory profile script..."
    if [ -f "$SCRIPT_DIR/kagglelink-directory.sh" ]; then
        install -m 755 "$SCRIPT_DIR/kagglelink-directory.sh" /etc/profile.d/kagglelink-directory.sh
    fi
    # Ensure it also runs for non-login interactive shells (idempotent)
    if ! grep -q 'kagglelink-directory' /root/.bashrc 2>/dev/null; then
        echo '[ -f /etc/profile.d/kagglelink-directory.sh ] && . /etc/profile.d/kagglelink-directory.sh' >> /root/.bashrc
    fi
}

start_ssh_service() {
    mkdir -p "$LOG_DIR"
    service ssh restart
    log "SSH service running on port ${SSH_PORT}."
}

setup_environment_variables
install_packages
install_zrok
setup_ssh_directory
configure_sshd
copy_vscode_dir
install_helper_commands
setup_default_directory
start_ssh_service

log "Setup script completed. Use start_zrok.sh to start the tunnel."
