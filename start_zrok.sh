#!/bin/bash
#
# start_zrok.sh - enable zrok and start the SSH tunnel share
#
# Usage: ./start_zrok.sh <zrok_token> [ssh_port] [--foreground] [--share-name NAME]
#
# Default mode runs the share in the BACKGROUND with an auto-restart
# supervisor, so the Kaggle notebook cell is released. A reserved share
# is used when possible so the access token stays stable across restarts.
#
set -euo pipefail

GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
BLUE='\033[0;34m'
BOLD='\033[1m'
NC='\033[0m'

if [ "$#" -lt 1 ]; then
    echo -e "${RED}Error:${NC} zrok token required"
    echo -e "${BOLD}Usage:${NC} ./start_zrok.sh <zrok_token> [ssh_port] [--foreground] [--share-name NAME]"
    exit 1
fi

ZROK_TOKEN=$1
shift
SSH_PORT=22
FOREGROUND=false
SHARE_NAME="kagglelink"

while [ "$#" -gt 0 ]; do
    case $1 in
        --foreground)  FOREGROUND=true; shift ;;
        --share-name)  SHARE_NAME="$2"; shift 2 ;;
        *)             SSH_PORT="$1"; shift ;;
    esac
done

LOG_DIR="/var/log/kagglelink"
ZROK_LOG="$LOG_DIR/zrok.log"
SUPERVISOR="/usr/local/bin/kagglelink-zrok-run"
mkdir -p "$LOG_DIR"

# --- Enable zrok (idempotent) -------------------------------------------
if zrok status 2>/dev/null | grep -q '<<SET>>'; then
    echo -e "${BLUE}zrok is already enabled for this environment; skipping enable.${NC}"
else
    echo -e "${BLUE}Enabling zrok with provided token...${NC}"
    zrok enable "$ZROK_TOKEN" || {
        echo -e "${RED}Failed to enable zrok with the provided token.${NC}"
        echo -e "${YELLOW}If your plan's environment limit is reached, release an old environment at your zrok dashboard or run 'zrok disable' on the stale machine.${NC}"
        exit 1
    }
fi

# --- Try to create a reserved share (stable access token) ---------------
SHARE_MODE="ephemeral"
if zrok reserve private --unique-name "$SHARE_NAME" --backend-mode tcpTunnel "localhost:${SSH_PORT}" >>"$ZROK_LOG" 2>&1; then
    SHARE_MODE="reserved"
    echo -e "${GREEN}Reserved share '${SHARE_NAME}' created.${NC}"
elif zrok overview 2>/dev/null | grep -q "\"${SHARE_NAME}\""; then
    SHARE_MODE="reserved"
    echo -e "${BLUE}Reserved share '${SHARE_NAME}' already exists; reusing it.${NC}"
else
    echo -e "${YELLOW}Could not create a reserved share (plan limit or older zrok?). Falling back to an ephemeral share.${NC}"
fi

# --- Foreground mode (old behaviour, used by tests) ----------------------
if [ "$FOREGROUND" = true ]; then
    echo -e "${BLUE}Starting zrok share in the foreground on port ${SSH_PORT}...${NC}"
    if [ "$SHARE_MODE" = "reserved" ]; then
        exec zrok share reserved "$SHARE_NAME" --headless
    else
        exec zrok share private --headless --backend-mode tcpTunnel "localhost:${SSH_PORT}"
    fi
fi

# --- Background mode with auto-restart supervisor ------------------------
cat > "$SUPERVISOR" <<EOF
#!/bin/bash
# Auto-generated by start_zrok.sh - restarts the zrok share if it drops.
LOG="$ZROK_LOG"
ATTEMPT=0
while [ "\$ATTEMPT" -lt 100 ]; do
    ATTEMPT=\$((ATTEMPT + 1))
    echo "[\$(date '+%F %T')] starting zrok share (attempt \$ATTEMPT, mode: $SHARE_MODE)" >> "\$LOG"
    if [ "$SHARE_MODE" = "reserved" ]; then
        zrok share reserved "$SHARE_NAME" --headless >> "\$LOG" 2>&1
    else
        zrok share private --headless --backend-mode tcpTunnel "localhost:${SSH_PORT}" >> "\$LOG" 2>&1
    fi
    echo "[\$(date '+%F %T')] zrok share exited; restarting in 5s" >> "\$LOG"
    sleep 5
done
EOF
chmod +x "$SUPERVISOR"

# Kill any previous supervisor/share before starting a new one
pkill -f "kagglelink-zrok-run" 2>/dev/null || true
pkill -f "zrok share" 2>/dev/null || true
sleep 1

echo -e "${BLUE}Starting zrok share in the background (port ${SSH_PORT})...${NC}"
: > "$ZROK_LOG"
nohup setsid "$SUPERVISOR" >/dev/null 2>&1 &

# --- Report the access token ---------------------------------------------
if [ "$SHARE_MODE" = "reserved" ]; then
    ACCESS_TOKEN="$SHARE_NAME"
else
    # Ephemeral shares print their token to the log; wait for it.
    ACCESS_TOKEN=""
    for _ in $(seq 1 30); do
        ACCESS_TOKEN=$(grep -oE 'zrok access private [[:alnum:]]+' "$ZROK_LOG" 2>/dev/null | tail -n 1 | awk '{print $4}')
        [ -n "$ACCESS_TOKEN" ] && break
        sleep 2
    done
fi

sleep 2
if ! pgrep -f "zrok share" >/dev/null; then
    echo -e "${RED}zrok share does not appear to be running. Last log lines:${NC}"
    tail -n 20 "$ZROK_LOG"
    exit 1
fi

echo ""
echo -e "${GREEN}${BOLD}Tunnel is up.${NC}"
if [ -n "${ACCESS_TOKEN:-}" ]; then
    echo -e "${GREEN}On your LOCAL machine, run:${NC}"
    echo -e "${BOLD}    zrok access private ${ACCESS_TOKEN}${NC}"
    echo -e "${GREEN}then SSH to the address it prints (e.g. ssh -p 9191 root@127.0.0.1).${NC}"
else
    echo -e "${YELLOW}Could not detect the access token automatically. Check the log:${NC}"
    echo "    tail -f $ZROK_LOG"
fi
echo -e "${BLUE}Tunnel log: ${ZROK_LOG} | Health check: kagglelink-status${NC}"
